L = [r"% generated by tools/fig3/numbers_r3.py -- do not edit by hand",
     r"\providecommand{\res}[3]{\ifcsname r@#1@#2@#3\endcsname\csname r@#1@#2@#3\endcsname\else\textbf{??}\fi}"]


def put(g, k, f, v):
    L.append(r"\expandafter\def\csname r@" + f"{g}@{k}@{f}" + r"\endcsname{" + str(v) + "}")


def f3(x):
    return f"{x:.3f}"


def p1(x):
    return f"{100 * x:.1f}"


EPKEY = {"succ": "success_rate", "all": "all_found", "ttd": "ttd_all", "surv": "survival_score"}


def episode_values(src, k):
    """Per-episode values of metric k from an evaluation directory (eval_misspec or formal format)."""
    p = Path(src) / "episodes.jsonl"
    if p.exists():
        rows = [json.loads(line) for line in open(p)]
        if rows and "success_rate" in rows[0]:
            return np.array([r[EPKEY[k]] for r in rows if r.get(EPKEY[k]) is not None], float)
    sp = Path(src) / "summary.json"
    if not sp.exists():
        return np.array([])
    out = []
    for r in json.load(open(sp)).get("records", []):
        info = r["info"]
        if k == "all":
            out.append(float(info["success_rate"] >= 1 - 1e-9))
        elif EPKEY[k] in info:
            out.append(info[EPKEY[k]])
    return np.array(out, float)


def summ(d):
    p = Path(d) / "summary.json"
    if not p.exists():
        return None
    s = json.load(open(p))
    g = lambda k: s[k]["mean"] if isinstance(s.get(k), dict) else s.get(k)  # noqa: E731
    return dict(succ=g("success_rate"), all=s.get("complete_rescue"), ttd=g("ttd_all"))


def se(d, k="succ"):
    """Standard error over evaluation episodes of a deterministic run; None if unavailable."""
    ep = episode_values(d, k)
    return float(ep.std(ddof=1) / np.sqrt(len(ep))) if len(ep) > 1 else None


# ---------------------------------------------------------------- per method and split
for m, by in RES.items():
    for sp, rows in by.items():
        if not rows:
            continue
        for key in ("succ", "all", "ttd", "surv"):
            v = np.array([r[key] for r in rows if r.get(key) is not None], float)
            if not len(v):
                continue
            put(m, sp, key, f3(v.mean()))
            put(m, sp, key + "pct", p1(v.mean()))
            if len(v) > 1:
                put(m, sp, key + "sd", f3(v.std(ddof=1)))
                put(m, sp, key + "sdpct", p1(v.std(ddof=1)))
            elif rows[0].get("src"):
                # deterministic: standard error over the evaluation episodes (same convention as Table 2)
                ep = episode_values(rows[0]["src"], key)
                if len(ep) > 1:
                    put(m, sp, key + "sd", f3(ep.std(ddof=1) / np.sqrt(len(ep))))
                    put(m, sp, key + "sdpct", p1(ep.std(ddof=1) / np.sqrt(len(ep))))
        put(m, sp, "n", len(rows))
        put(m, sp, "eps", rows[0].get("n") or "")

