"""Write every number cited in the manuscript text as a LaTeX macro, straight from the result files.

Usage in the manuscript:  \res{<group>}{<key>}{<field>}, e.g. \res{anchor30}{test}{succpct}.
Undefined entries print a bold ?? so a missing result cannot go unnoticed.
Output: runs/complete-paper-v4/tables-r3/numbers_r3.tex
"""
